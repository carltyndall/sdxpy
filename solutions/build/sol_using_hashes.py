"""
Hash-based staleness detection for the build manager.

This module provides two pieces:
1. build_init.py logic: scans all files mentioned in a build config,
   computes their SHA-256 hashes, and stores them in build_hash.json.
2. A BuildHash class that checks current file hashes against stored hashes
   to determine staleness, then updates the hash file after a build.
"""

import hashlib
import json
import os
import sys


def compute_hash(filepath):
    """Return the SHA-256 hex digest of a file's contents."""
    hasher = hashlib.sha256()
    try:
        with open(filepath, "rb") as f:
            while True:
                chunk = f.read(8192)
                if not chunk:
                    break
                hasher.update(chunk)
    except FileNotFoundError:
        return None
    return hasher.hexdigest()


def build_init(config_path, hash_path="build_hash.json"):
    """Compute hashes for every file mentioned in a build configuration
    and store them alongside the file names in a JSON file."""
    with open(config_path, "r") as f:
        config = json.load(f)

    # Collect all targets that are actual filenames (not phony)
    filenames = set()
    for name, details in config.items():
        # Target name and its dependencies may correspond to files
        filenames.add(name)
        for dep in details.get("depends", []):
            filenames.add(dep)

    hashes = {}
    for filename in sorted(filenames):
        filehash = compute_hash(filename)
        if filehash is not None:
            hashes[filename] = filehash
        else:
            hashes[filename] = None

    with open(hash_path, "w") as f:
        json.dump(hashes, f, indent=2)

    print(f"Stored hashes for {len(hashes)} files in {hash_path}")
    return hashes


class BuildHash:
    """Build manager that uses file hashes to determine staleness."""

    def __init__(self, hash_path="build_hash.json"):
        self.hash_path = hash_path
        self._stored_hashes = self._load_hashes()

    def _load_hashes(self):
        try:
            with open(self.hash_path, "r") as f:
                return json.load(f)
        except FileNotFoundError:
            return {}

    def _save_hashes(self, hashes):
        with open(self.hash_path, "w") as f:
            json.dump(hashes, f, indent=2)

    def build(self, config):
        config = self._configure(config)
        ordered = self._topo_sort(config)
        actions = []

        for node in ordered:
            if self._needs_update(config, node):
                self._refresh(config, node, actions)

        # After building, update stored hashes for all targets that were built
        self._update_hashes(config, actions)
        return actions

    def _needs_update(self, config, node):
        """A target needs updating if any of its dependencies have changed
        hash since the last build, or if the target itself has no stored hash."""
        target_hash = compute_hash(node)
        stored_target = self._stored_hashes.get(node)

        # Target doesn't exist yet — needs building
        if target_hash is None:
            return True

        # Target was never hashed before — needs building
        if stored_target is None:
            return True

        # Check if any dependency's current hash differs from stored
        for dep in config[node].get("depends", []):
            current = compute_hash(dep)
            stored = self._stored_hashes.get(dep)
            if current != stored:
                return True

        return False

    def _refresh(self, config, node, actions):
        assert node in config, f"Unknown node {node}"
        # In a real build manager this would run a shell command.
        # For demonstration we record the action.
        actions.append(config[node]["rule"])
        # Simulate creating/updating the file
        with open(node, "w") as f:
            f.write(f"# Generated by rule: {config[node]['rule']}\n")

    def _update_hashes(self, config, actions):
        """Recompute and store hashes for all targets after a build."""
        for node in config:
            filehash = compute_hash(node)
            if filehash is not None:
                self._stored_hashes[node] = filehash
        self._save_hashes(self._stored_hashes)

    def _must(self, condition, message):
        if not condition:
            raise ValueError(message)

    def _configure(self, config):
        known = set(config.keys())
        return {
            n: self._check(n, d, known)
            for n, d in config.items()
        }

    def _check(self, name, details, known):
        self._check_keys(name, details)
        depends = set(details["depends"])
        self._must(
            depends.issubset(known),
            f"Unknown depends for {name}",
        )
        result = details.copy()
        result["depends"] = depends
        return result

    def _check_keys(self, name, details):
        self._must(
            "rule" in details,
            f"Missing rule for {name}",
        )
        self._must(
            "depends" in details,
            f"Missing depends for {name}",
        )

    def _topo_sort(self, config):
        graph = {n: config[n]["depends"] for n in config}
        result = []
        while graph:
            available = {n for n in graph if not graph[n]}
            self._must(
                available,
                f"Circular graph {list(graph.keys())}",
            )
            result.extend(sorted(available))
            graph = {
                n: graph[n] - available
                for n in graph
                if n not in available
            }
        return result


def main():
    import tempfile
    import shutil

    tmpdir = tempfile.mkdtemp()
    os.chdir(tmpdir)

    # Create some input "files" with known content
    for name, content in [
        ("raw.csv", "a,b,c\n1,2,3\n"),
        ("normalize.py", "print('normalize')\n"),
        ("controls.csv", "x,y\n4,5\n"),
        ("analyze.py", "print('analyze')\n"),
        ("plot.py", "print('plot')\n"),
    ]:
        with open(name, "w") as f:
            f.write(content)

    config = {
        "collated.csv": {
            "depends": ["samples.csv", "controls.csv"],
            "rule": "python analyze.py > collated.csv",
        },
        "samples.csv": {
            "depends": ["normalize.py", "raw.csv"],
            "rule": "python normalize.py > samples.csv",
        },
        "controls.csv": {
            "depends": [],
            "rule": "echo 'x,y' > controls.csv",
        },
        "raw.csv": {
            "depends": [],
            "rule": "echo 'a,b' > raw.csv",
        },
        "normalize.py": {
            "depends": [],
            "rule": "echo 'pass' > normalize.py",
        },
        "analyze.py": {
            "depends": [],
            "rule": "echo 'pass' > analyze.py",
        },
    }

    # Save config
    config_path = os.path.join(tmpdir, "build.json")
    with open(config_path, "w") as f:
        json.dump(config, f, indent=2)

    # Step 1: initialize hashes
    print("=== build_init ===")
    hash_path = os.path.join(tmpdir, "build_hash.json")
    build_init(config_path, hash_path)

    with open(hash_path, "r") as f:
        stored = json.load(f)
    print(f"Stored hashes: {json.dumps(stored, indent=2)}")

    # Step 2: first build — nothing should change since hashes match
    print("\n=== First build (should be empty — nothing stale) ===")
    builder = BuildHash(hash_path)
    actions = builder.build(config)
    print(f"Actions: {actions}")

    # Step 3: modify a dependency — things should become stale
    print("\n=== After modifying raw.csv ===")
    with open("raw.csv", "w") as f:
        f.write("a,b,c\n6,7,8\n")

    builder2 = BuildHash(hash_path)
    actions = builder2.build(config)
    print(f"Actions: {actions}")

    # Cleanup
    os.chdir("/")
    shutil.rmtree(tmpdir)


if __name__ == "__main__":
    main()
